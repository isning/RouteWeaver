package httpapi

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// Vite's default output uses an eight-character URL-safe content fingerprint.
// The spelling alone is not authority: only entries in this build's manifest
// whose exact bytes were read at startup may receive immutable cache headers.
var builtUIAssetName = regexp.MustCompile(`^assets/[A-Za-z0-9_.-]+-[A-Za-z0-9_-]{8}\.(js|css|woff2?)$`)

const maxUIAssetBytes = 16 << 20
const immutableUICache = "public, max-age=31536000, immutable"

type uiManifestEntry struct {
	File    string   `json:"file"`
	CSS     []string `json:"css"`
	Assets  []string `json:"assets"`
	IsEntry bool     `json:"isEntry"`
}

// Failed/missing manifests disable the optimization, not the application. The
// manifest is generated by the normal production build and packaged with dist.
func readBuiltUIAssets(directory string) map[string][sha256.Size]byte {
	assets := make(map[string][sha256.Size]byte)
	body, _, err := readRegularUIFile(filepath.Join(directory, ".vite", "manifest.json"), 4<<20)
	if err != nil {
		return assets
	}
	var manifest map[string]uiManifestEntry
	if json.Unmarshal(body, &manifest) != nil || !manifest["index.html"].IsEntry || !builtUIAssetName.MatchString(manifest["index.html"].File) {
		return assets
	}
	for _, entry := range manifest {
		names := append(append([]string{entry.File}, entry.CSS...), entry.Assets...)
		for _, name := range names {
			if !builtUIAssetName.MatchString(name) {
				continue
			}
			if _, exists := assets["/"+name]; exists {
				continue
			}
			body, _, err := readRegularUIFile(filepath.Join(directory, filepath.FromSlash(name)), maxUIAssetBytes)
			if err == nil {
				assets["/"+name] = sha256.Sum256(body)
			}
		}
	}
	return assets
}

func readRegularUIFile(path string, limit int64) ([]byte, time.Time, error) {
	entry, err := os.Lstat(path)
	if err != nil {
		return nil, time.Time{}, err
	}
	if !entry.Mode().IsRegular() || entry.Size() > limit {
		return nil, time.Time{}, os.ErrInvalid
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, time.Time{}, err
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil {
		return nil, time.Time{}, err
	}
	if !info.Mode().IsRegular() || !os.SameFile(entry, info) || info.Size() > limit {
		return nil, time.Time{}, os.ErrInvalid
	}
	body, err := io.ReadAll(io.LimitReader(file, limit+1))
	if err != nil {
		return nil, time.Time{}, err
	}
	if int64(len(body)) > limit {
		return nil, time.Time{}, os.ErrInvalid
	}
	return body, info.ModTime(), nil
}

func serveUI(directory string) http.HandlerFunc {
	assets := readBuiltUIAssets(directory)
	return func(writer http.ResponseWriter, r *http.Request) {
		w := &uiResponse{ResponseWriter: writer}
		if strings.HasPrefix(r.URL.Path, "/api/") || strings.HasPrefix(r.URL.Path, "/feed/") {
			fail(w, 404, "not found")
			return
		}
		rel := filepath.Clean("/" + r.URL.Path)
		path := filepath.Join(directory, rel)
		// Reject normalized/encoded aliases for caching. The existing static/SPA
		// behavior remains available below, with the default no-store policy.
		if expected, ok := assets[r.URL.Path]; ok && r.URL.RawPath == "" && rel == r.URL.Path {
			body, modified, err := readRegularUIFile(path, maxUIAssetBytes)
			if err == nil && sha256.Sum256(body) == expected {
				// Serve the verified byte snapshot, not a second file read that could
				// observe a concurrent deployment. Changed/missing files are uncached.
				w.allowImmutable = true
				http.ServeContent(w, r, filepath.Base(path), modified, bytes.NewReader(body))
				return
			}
		}
		if info, err := os.Stat(path); err == nil && !info.IsDir() {
			http.ServeFile(w, r, path)
			return
		}
		http.ServeFile(w, r, filepath.Join(directory, "index.html"))
	}
}

// ServeFile/ServeContent may remove cache headers on error. Reassert the policy
// at the final status boundary for every static response, including SPA fallback.
// Security headers and all non-static response policies remain with headers().
type uiResponse struct {
	http.ResponseWriter
	wroteHeader    bool
	allowImmutable bool
}

func (w *uiResponse) WriteHeader(status int) {
	if w.wroteHeader {
		return
	}
	w.wroteHeader = true
	if w.allowImmutable && (status == http.StatusOK || status == http.StatusPartialContent || status == http.StatusNotModified) {
		w.Header().Set("Cache-Control", immutableUICache)
	} else {
		w.Header().Set("Cache-Control", "no-store")
	}
	w.ResponseWriter.WriteHeader(status)
}

func (w *uiResponse) Write(body []byte) (int, error) {
	if !w.wroteHeader {
		w.WriteHeader(http.StatusOK)
	}
	return w.ResponseWriter.Write(body)
}
