package managedxray_test

import (
	"encoding/json"
	"io"
	"net"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"routeweaver/internal/entrypolicy"
	managed "routeweaver/runtimes/xray"
)

func TestJournalPersistsCompleteDrainedNativeTrafficBeforeNextEpoch(t *testing.T) {
	for _, obstructFinal := range []bool{false, true} {
		name := "clean final"
		if obstructFinal {
			name = "failed final write"
		}
		t.Run(name, func(t *testing.T) {
			echo, err := net.Listen("tcp", "127.0.0.1:0")
			if err != nil {
				t.Fatal(err)
			}
			defer echo.Close()
			go func() {
				c, err := echo.Accept()
				if err != nil {
					return
				}
				defer c.Close()
				_, _ = io.Copy(c, c)
			}()
			port := freePort(t)
			d := descriptor()
			d.DestinationPolicy.AllowCIDRs = []string{"127.0.0.1/32"}
			r, err := managed.New(config(port), d, newLeaseService(0))
			if err != nil {
				t.Fatal(err)
			}
			defer r.Close()
			dir := filepath.Join(t.TempDir(), "journal")
			baseline := r.Snapshot()
			journal, err := managed.BeginJournal(dir, baseline)
			if err != nil {
				t.Fatal(err)
			}
			if err = r.Start(); err != nil {
				t.Fatal(err)
			}
			c := dialVLESS(t, port, echo.Addr().(*net.TCPAddr).Port, "127.0.0.1", false, nil)
			defer c.Close()
			payload := []byte("count these actual native bytes")
			if err = roundtrip(c, payload, true); err != nil {
				t.Fatal(err)
			}
			// Close the runtime with the real stream still open: final evidence
			// must come after its I/O and settlement drain, never from baseline.
			if err = r.Close(); err != nil {
				t.Fatal(err)
			}
			final := r.Snapshot()
			if final.ActiveFlows != 0 || len(final.Counters) != 1 || final.Counters[0].UploadBytes != uint64(len(payload)) || final.Counters[0].DownloadBytes != uint64(len(payload)) || final.Counters[0].CumulativeBytes != uint64(2*len(payload)) {
				t.Fatalf("incomplete native final counters: %+v", final)
			}
			finalPath := filepath.Join(dir, final.CounterEpoch+".final.json")
			if obstructFinal {
				if err = os.WriteFile(finalPath, []byte("partial write evidence"), 0600); err != nil {
					t.Fatal(err)
				}
			}
			err = journal.Finish(final)
			if obstructFinal {
				if err == nil {
					t.Fatal("final write obstruction accepted")
				}
				b, readErr := os.ReadFile(finalPath)
				if readErr != nil || string(b) != "partial write evidence" {
					t.Fatal("failed final evidence changed", readErr)
				}
				if _, err = os.Stat(filepath.Join(dir, "running.json")); err != nil {
					t.Fatal("running marker lost", err)
				}
			} else {
				if err != nil {
					t.Fatal(err)
				}
				b, err := os.ReadFile(finalPath)
				if err != nil {
					t.Fatal(err)
				}
				var persisted entrypolicy.Snapshot
				if err = json.Unmarshal(b, &persisted); err != nil {
					t.Fatal(err)
				}
				if !reflect.DeepEqual(final, persisted) {
					t.Fatalf("final snapshot changed: got %+v, want %+v", persisted, final)
				}
			}
			// The next baseline is generated by a new real runtime, not reset
			// counters or a replacement journal directory.
			next, err := managed.New(config(port), d, newLeaseService(0))
			if err != nil {
				t.Fatal(err)
			}
			defer next.Close()
			if next.Snapshot().CounterEpoch == baseline.CounterEpoch {
				t.Fatal("runtime reused counter epoch")
			}
			nextJournal, err := managed.BeginJournal(dir, next.Snapshot())
			if obstructFinal {
				if err == nil {
					t.Fatal("uncertain final permitted fresh epoch")
				}
			} else {
				if err != nil {
					t.Fatal(err)
				}
				if err = next.Close(); err != nil {
					t.Fatal(err)
				}
				if err = nextJournal.Finish(next.Snapshot()); err != nil {
					t.Fatal(err)
				}
			}
		})
	}
}

func TestJournalInvalidFinalRetainsRealEpochEvidence(t *testing.T) {
	for _, invalid := range []string{"active flows", "wrong epoch"} {
		t.Run(invalid, func(t *testing.T) {
			r, err := managed.New(config(freePort(t)), descriptor(), newLeaseService(0))
			if err != nil {
				t.Fatal(err)
			}
			defer r.Close()
			dir := filepath.Join(t.TempDir(), "journal")
			baseline := r.Snapshot()
			journal, err := managed.BeginJournal(dir, baseline)
			if err != nil {
				t.Fatal(err)
			}
			if err = r.Close(); err != nil {
				t.Fatal(err)
			}
			// Deliberately corrupt only the rejected input. This is negative
			// validation coverage, not a claimed successful runtime observation.
			invalidFinal := r.Snapshot()
			if invalid == "active flows" {
				invalidFinal.ActiveFlows = 1
			} else {
				invalidFinal.CounterEpoch = "wrong-epoch"
			}
			if err = journal.Finish(invalidFinal); err == nil {
				t.Fatal("invalid final accepted")
			}
			if _, err = os.Stat(filepath.Join(dir, "running.json")); err != nil {
				t.Fatal("running marker lost", err)
			}
			finals, err := filepath.Glob(filepath.Join(dir, "*.final.json"))
			if err != nil || len(finals) != 0 {
				t.Fatalf("invalid final persisted: %v: %v", finals, err)
			}
			if _, err = managed.BeginJournal(dir, baseline); err == nil {
				t.Fatal("invalid final authorized new epoch")
			}
		})
	}
}
