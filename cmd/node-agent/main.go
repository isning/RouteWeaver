// node-agent is an explicitly local reconciliation harness. It has no server,
// enrollment flow or remote shell API. Outbound transport requires explicit scope.
package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"
	"time"

	"routeweaver/internal/agent"
	"routeweaver/internal/domain"
)

func main() {
	ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer cancel()
	os.Exit(run(ctx, os.Args[1:], os.Stdout, os.Stderr))
}
func run(ctx context.Context, args []string, out, errOut io.Writer) int {
	flags := flag.NewFlagSet("node-agent", flag.ContinueOnError)
	flags.SetOutput(errOut)
	stateDir := flags.String("state-dir", "", "private local storage directory (required)")
	desiredFile := flags.String("desired", "", "local Desired JSON file; never a URL")
	mode := flags.String("mode", "fixture", "fixture, check, supervise, or catalog")
	operation := flags.String("operation", "reconcile", "reconcile, recover, or status")
	binary := flags.String("binary", "", "absolute trusted native core executable path")
	coreStore := flags.String("core-store", "", "private immutable official-release store; required by catalog mode")
	maxLease := flags.Duration("max-policy-lease", 0, "explicit maximum policy lease, e.g. 15m (required)")
	allowProcess := flags.Bool("allow-local-process", false, "allow a locally owned core process; does not install a service")
	service := flags.Bool("service", false, "explicit foreground outbound service until SIGINT/SIGTERM; mutually exclusive with run-for")
	runFor := flags.Duration("run-for", 0, "supervised session duration, at most 1h; stops owned process on exit")
	demo := flags.Bool("demo", false, "generate synthetic local-fixture Desired state; no proxy process")
	controlPlane := flags.String("control-plane", "", "explicit HTTPS control-plane origin; no default remote connection")
	tokenFile := flags.String("token-file", "", "private operator-provided scoped token file; never generated by this command")
	allowLoopbackHTTP := flags.Bool("allow-loopback-http", false, "test-only HTTP to literal loopback origin")
	nodeID := flags.String("node-id", "", "enrolled node identity for outbound mode")
	instanceID := flags.String("instance-id", "", "enrolled instance identity for outbound mode")
	epoch := flags.String("enrollment-epoch", "", "operator-provided enrolled epoch")
	adapterID := flags.String("adapter", agent.LocalFixtureID, "exact trusted adapter ID for outbound mode")
	version := flags.String("core-version", "1", "exact core version for outbound mode")
	meterEpoch := flags.String("meter-stream-epoch", "", "optional explicit durable meter outbox epoch")
	enableDiagnostics := flags.Bool("diagnostics", true, "process bounded administrator-authorized public HTTPS diagnostic jobs in outbound mode")
	observeNode := flags.Bool("observe-node", false, "read bounded Linux procfs resource/NIC counters; enable only on the designated instance per node")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	if *stateDir == "" || *maxLease <= 0 || flags.NArg() != 0 {
		fmt.Fprintln(errOut, "state-dir and positive max-policy-lease are required")
		return 2
	}
	runForSet := false
	flags.Visit(func(f *flag.Flag) {
		if f.Name == "run-for" {
			runForSet = true
		}
	})
	if *service && (*controlPlane == "" || runForSet) {
		fmt.Fprintln(errOut, "service requires outbound control-plane mode and no run-for")
		return 2
	}
	if *observeNode && *controlPlane == "" {
		fmt.Fprintln(errOut, "observe-node requires explicitly enrolled outbound control-plane mode")
		return 2
	}
	var d agent.Desired
	if *controlPlane != "" {
		if *demo || *desiredFile != "" || *tokenFile == "" || (!*service && (*runFor <= 0 || *runFor > time.Hour)) || *mode == "check" || *operation != "reconcile" {
			fmt.Fprintln(errOut, "outbound mode requires token-file and either service or bounded run-for, no demo/desired/check/status")
			return 2
		}
		d.Scope = agent.Scope{NodeID: *nodeID, InstanceID: *instanceID, EnrollmentEpoch: *epoch}
		d.AdapterID = *adapterID
		d.CoreVersion = *version
	} else if *demo {
		if *mode != "fixture" || *desiredFile != "" {
			fmt.Fprintln(errOut, "demo requires fixture mode and no desired file")
			return 2
		}
		now := time.Now().UTC()
		artifacts := []domain.Artifact{{Path: "config.json", Content: `{"fixture":"local only"}`}}
		digest, _ := agent.ArtifactDigest(artifacts)
		d = agent.Desired{Scope: agent.Scope{NodeID: "local-node", InstanceID: "fixture-core", EnrollmentEpoch: "local-only"}, AdapterID: agent.LocalFixtureID, CoreVersion: "1", Generation: 1, RevisionID: "demo-revision", OperationID: "demo-operation", Digest: digest, EntryFile: "config.json", Artifacts: artifacts, Lease: agent.PolicyLease{Revision: "demo-policy", IssuedAt: now, ExpiresAt: now.Add(*maxLease), AccessAllowed: true, QuotaCertain: true}}
	} else {
		if *desiredFile == "" {
			fmt.Fprintln(errOut, "desired file required, or use --demo for local fixture")
			return 2
		}
		f, err := os.Open(*desiredFile)
		if err != nil {
			fmt.Fprintln(errOut, "cannot open local desired file")
			return 2
		}
		defer f.Close()
		decoder := json.NewDecoder(io.LimitReader(f, 12<<20))
		decoder.DisallowUnknownFields()
		if err = decoder.Decode(&d); err != nil {
			fmt.Fprintln(errOut, "invalid desired JSON")
			return 2
		}
		var extra any
		if decoder.Decode(&extra) != io.EOF {
			fmt.Fprintln(errOut, "trailing desired JSON")
			return 2
		}
	}
	if d.AdapterID == agent.ManagedXrayID && *mode == "supervise" && (*controlPlane == "" || *meterEpoch == "") {
		fmt.Fprintln(errOut, "managed supervision requires enrolled control-plane admission and an explicit durable meter-stream-epoch")
		return 2
	}
	var adapter agent.Adapter
	options := agent.Options{MaxLease: *maxLease}
	switch *mode {
	case "catalog":
		if *coreStore == "" || *binary != "" || *controlPlane == "" {
			fmt.Fprintln(errOut, "catalog mode requires core-store and an explicitly enrolled outbound session, with no arbitrary binary path")
			return 2
		}
		installer, installErr := agent.NewCoreInstaller(*coreStore, agent.CoreInstallerOptions{})
		if installErr != nil {
			fmt.Fprintln(errOut, installErr)
			return 2
		}
		options.CoreInstaller = installer
		if *allowProcess {
			options.InstallSupervisor = &agent.SupervisorOptions{AllowLocalProcess: true, StartupGrace: 200 * time.Millisecond, StopTimeout: 2 * time.Second}
		}

	case "fixture":
		adapter = agent.LocalFixture{}
	case "check", "supervise":
		checker, err := agent.NewNativeChecker(d.AdapterID, d.CoreVersion, *binary, 5*time.Second)
		if err != nil {
			fmt.Fprintln(errOut, err)
			return 2
		}
		adapter = checker
		if *mode == "supervise" {
			if !*allowProcess || (!*service && (*runFor <= 0 || *runFor > time.Hour)) {
				fmt.Fprintln(errOut, "supervise requires allow-local-process and service or run-for in (0,1h]")
				return 2
			}
			supervisor, err := agent.NewProcessSupervisor(checker, agent.SupervisorOptions{AllowLocalProcess: true, StartupGrace: 200 * time.Millisecond, StopTimeout: 2 * time.Second})
			if err != nil {
				fmt.Fprintln(errOut, err)
				return 2
			}
			adapter = supervisor
		}
	default:
		fmt.Fprintln(errOut, "unknown mode")
		return 2
	}
	registry := agent.NewRegistry()
	if adapter != nil {
		if err := registry.Register(adapter); err != nil {
			fmt.Fprintln(errOut, err)
			return 2
		}
	}
	r, err := agent.Open(*stateDir, d.Scope, registry, options)
	if err != nil {
		fmt.Fprintln(errOut, err)
		return 1
	}
	defer r.Close()
	if *mode == "supervise" && *operation == "reconcile" {
		defer func() {
			stopCtx, cancel := context.WithTimeout(context.Background(), 4*time.Second)
			defer cancel()
			if _, stopErr := r.StopOwned(stopCtx); stopErr != nil {
				fmt.Fprintln(errOut, "owned-process cleanup requires reconciliation:", stopErr)
			}
		}()
	}
	encode := func(st agent.State) error { return json.NewEncoder(out).Encode(st) }
	if *controlPlane != "" {
		info, tokenErr := os.Lstat(*tokenFile)
		if tokenErr != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 || info.Size() > 8192 {
			fmt.Fprintln(errOut, "token-file must be an existing private regular file")
			return 2
		}
		tokenBytes, tokenErr := os.ReadFile(*tokenFile)
		if tokenErr != nil {
			fmt.Fprintln(errOut, "cannot read scoped token file")
			return 2
		}
		transport, transportErr := agent.NewHTTPTransport(agent.HTTPTransportOptions{BaseURL: *controlPlane, Token: strings.TrimSpace(string(tokenBytes)), Scope: d.Scope, RequestTimeout: 5 * time.Second, MaxAttempts: 3, Backoff: 250 * time.Millisecond, AllowLoopbackHTTP: *allowLoopbackHTTP})
		if transportErr != nil {
			fmt.Fprintln(errOut, transportErr)
			return 2
		}
		defer transport.Close()
		var spool *agent.MeterSpool
		if *meterEpoch != "" {
			spool, err = agent.OpenMeterSpool(filepath.Join(r.Root(), "meters"), d.Scope, *meterEpoch)
			if err != nil {
				fmt.Fprintln(errOut, err)
				return 1
			}
			defer spool.Close()
		}
		var observer *agent.NodeObserver
		if *observeNode {
			collector, collectorErr := agent.NewLocalNodeCollector()
			if collectorErr != nil {
				fmt.Fprintln(errOut, collectorErr)
				return 2
			}
			observer, err = agent.NewNodeObserver(d.Scope, collector)
			if err != nil {
				fmt.Fprintln(errOut, err)
				return 2
			}
		}
		var diagnosticWorker *agent.DiagnosticWorker
		if *enableDiagnostics {
			diagnosticWorker, err = agent.OpenDiagnosticWorker(filepath.Join(r.Root(), "diagnostics"), d.Scope, agent.NewDiagnosticExecutor(agent.DiagnosticExecutorOptions{}))
			if err != nil {
				fmt.Fprintln(errOut, err)
				return 1
			}
			defer diagnosticWorker.Close()
		}
		final, driverErr := agent.RunDriver(ctx, r, transport, spool, agent.DriverOptions{Diagnostics: diagnosticWorker, NodeObserver: observer, PollInterval: time.Second, LeaseInterval: 250 * time.Millisecond, MaxRuntime: *runFor, Continuous: *service, OnTransportError: func(e error) { fmt.Fprintln(errOut, e) }})
		if encode(final) != nil {
			return 1
		}
		if driverErr != nil {
			fmt.Fprintln(errOut, driverErr)
			return 1
		}
		return 0
	}

	var st agent.State
	switch *operation {
	case "status":
		st = r.State()
	case "recover":
		st, err = r.Recover(ctx)
	case "reconcile":
		st, err = r.Submit(ctx, d)
	default:
		fmt.Fprintln(errOut, "unknown operation")
		return 2
	}
	if writeErr := encode(st); writeErr != nil {
		return 1
	}
	if err != nil {
		// Successful check mode deliberately reports activation_unverified, not apply.
		if *mode == "check" && errors.Is(err, agent.ErrUnsupportedActivation) && st.NativeChecked {
			return 0
		}
		fmt.Fprintln(errOut, err)
		return 1
	}
	if *mode != "supervise" || *operation != "reconcile" {
		return 0
	}
	timer := time.NewTimer(*runFor)
	defer timer.Stop()
	tick := time.NewTicker(250 * time.Millisecond)
	defer tick.Stop()
	result := 0
loop:
	for {
		select {
		case <-ctx.Done():
			break loop
		case <-timer.C:
			break loop
		case <-tick.C:
			st, err = r.EnforcePolicy(ctx)
			if err != nil {
				_ = encode(st)
				result = 1
				break loop
			}
			st, err = r.Recover(ctx)
			if err != nil || st.Phase != agent.ObservedConformant {
				_ = encode(st)
				result = 1
				break loop
			}
		}
	}
	// Always clean up this session, even when the caller's context was canceled.
	stopCtx, cancel := context.WithTimeout(context.Background(), 4*time.Second)
	defer cancel()
	st, err = r.StopOwned(stopCtx)
	if err != nil {
		fmt.Fprintln(errOut, err)
		result = 1
	}
	if encode(st) != nil {
		return 1
	}
	return result
}
