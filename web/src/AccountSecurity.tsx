function AccountRecovery({ session, recovery }: { session: Session; recovery: SecurityRecovery }) {
  const accounts = useQuery({
    queryKey: ["security-accounts"],
    queryFn: () => list<Account>("/admin/accounts"),
  });
  const [target, setTarget] = useState<Account | null>(null);
  return (
    <Section
      title="账号恢复与退役"
      description="账号身份与用户的服务授权是两套设置。停用或退役会阻止登录和订阅交付，并保留历史数据。"
    >
      <QueryState
        loading={accounts.isPending} paused={accounts.isPaused} loadingLayout="table"
        error={securityError(accounts.error)}
        retry={() => accounts.refetch()}
      >
        {accounts.data?.length === 0 && (
          <p className="text-sm text-muted-foreground">没有账号记录。</p>
        )}
        {Boolean(accounts.data?.length) && <ul className="divide-y rounded-lg border">
          {accounts.data?.map((account) => (
            <li
              key={account.id}
              aria-label={account.name}
              className="flex flex-wrap items-center justify-between gap-3 p-4"
            >
              <div className="min-w-0 space-y-1">
                <strong className="break-words text-sm">{account.name}</strong>
                <Metadata className="break-all text-sm text-muted-foreground">
                  <span>{account.username}</span>
                  <span>{account.role === "admin" ? "管理员" : "个人账号"}</span>
                </Metadata>
                <Badge variant="secondary">
                  {account.retired
                    ? "已永久退役"
                    : account.disabled
                      ? "已停用"
                      : account.passwordChangeRequired
                        ? "须更换密码"
                        : "可登录"}
                </Badge>
                {account.id === session.user.id && (
                  <p className="text-xs text-muted-foreground">
                    当前账号，请使用上方安全设置。
                  </p>
                )}
              </div>
              <ActionButton
                variant="outline"
                aria-label={`管理 ${account.name}`}
                disabled={recovery.blocked || account.id === session.user.id || account.retired}
                onClick={() => setTarget(account)}
              >
                管理账号
              </ActionButton>
            </li>
          ))}
        </ul>}
      </QueryState>
      {target && (
        <AccountRecoveryTask
          key={target.id}
          target={target}
          actor={session.user}
          recovery={recovery}
          onClose={() => setTarget(null)}
        />
      )}
    </Section>
  );
}
function AccountRecoveryTask({
  target,
  actor,
  recovery,
  onClose,
}: {
  target: Account;
  actor: Session["user"];
  recovery: SecurityRecovery;
  onClose: () => void;
}) {
  const [form] = useForm();
  const formId = useId();
  const action: SecurityAction =
    useWatch("action", form) || (target.disabled ? "enable" : "disable");
  const [dirty, setDirty] = useState(false);
  const { confirm, confirming } = useDiscardConfirmation(target.id);
  const active = useRef(true),
    submitting = useRef(false);
  useLayoutEffect(() => {
    active.current = true;
    return () => {
      active.current = false;
    };
  }, []);
  const client = useQueryClient();
  const save = useMutation({
    mutationFn: (value: {
      action: SecurityAction;
      reason: string;
      currentPassword: string;
      totp?: string;
      newPassword?: string;
    }) =>
      recovery.run(value.action, target.id, () => post<Account>(
        `/admin/accounts/${encodeURIComponent(target.id)}/security`,
        value,
      ), (result) => result?.id === target.id),
    retry: false,
    networkMode: "always",
    gcTime: 0,
    onError: () => {
      if (active.current && recovery.hasRecord()) {
        form.setFieldsValue({ currentPassword: "", totp: "", newPassword: "" });
      }
    },
    onSuccess: () => {
      if (!active.current) return;
      client.invalidateQueries({ queryKey: ["security-accounts"] });
      form.resetFields();
      setDirty(false);
      toast.success("账号安全设置已更新");
      onClose();
    },
    onSettled: (_data, _error, values) => {
      if (typeof values === "object") {
        for (const key of Object.keys(values)) Reflect.set(values, key, "");
      }
      submitting.current = false;
    },
  });
  useUnsavedChanges(dirty || save.isPending);
  const close = () => {
    if (save.isPending || submitting.current || confirming) return;
    if (!dirty) return onClose();
    confirm(
      {
        title: "放弃未提交的账号操作？",
        description: recovery.hasRecord() ? "上次操作结果仍未确认。关闭后可在账号安全页继续查看当前状态。" : "当前输入尚未提交，目标账号未因这些输入而改变。",
        confirmLabel: "放弃输入",
        cancelLabel: "继续编辑",
      },
      () => {
        if (active.current) onClose();
      },
    );
  };
  const options: SecurityAction[] = [
    target.disabled ? "enable" : "disable",
    "reset-password",
    ...(target.mfaEnabled ? ["reset-mfa" as const] : []),
    "retire",
  ];
  return (
    <TaskDialog
      scrollMode="auto"
      open
      title={`管理 ${target.name} 的账号`}
      description={`登录名：${target.username}`}
      onOpenChange={(open) => {
        if (!open) close();
      }}
      pending={save.isPending}
      footer={
        <div className="w-full space-y-3">
          <p className="text-sm text-muted-foreground">
            {actions[action].consequence}
          </p>
          <div className="flex flex-wrap justify-end gap-2">
            <ActionButton variant="outline" onClick={close}>
              取消
            </ActionButton>
            <ActionButton
              type="submit"
              form={formId}
              variant={action === "enable" ? "default" : "destructive"}
              pending={save.isPending}
              disabled={recovery.blocked}
            >
              {actions[action].label}
            </ActionButton>
          </div>
        </div>
      }
    >
      <AppForm
        id={formId}
        form={form}
        initialValues={{ action }}
        disabled={save.isPending || recovery.blocked}
        onValuesChange={() => setDirty(true)}
        onFinish={(values) => {
          if (!active.current || submitting.current || recovery.blocked) return;
          submitting.current = true;
          save.mutate({
            action,
            reason: values.reason,
            currentPassword: values.currentPassword,
            ...(values.totp ? { totp: values.totp } : {}),
            ...(action === "reset-password"
              ? { newPassword: values.newPassword }
              : {}),
          });
        }}
      >
        <SecurityRecoveryNotice recovery={recovery} pending={save.isPending} />
        <ErrorNotice error={securityError(save.error)} />
        <AppField name="action" label="账号操作" trigger="onValueChange">
          <ChoiceSelect
            options={options.map((value) => ({
              value,
              label: actions[value].label,
            }))}
          />
        </AppField>
        {action === "reset-password" && (
          <AppField
            name="newPassword"
            label="临时密码"
            description="使用 12–72 个 UTF-8 字节；中文通常每字占 3 字节。"
            rules={[{ required: true }, passwordRule]}
          >
            <PasswordInput autoComplete="new-password" />
          </AppField>
        )}
        {action === "retire" && (
          <AppField
            name="confirmTarget"
            label="输入登录名以确认永久退役"
            rules={[
              { required: true },
              {
                validator: (_rule, value) =>
                  value === target.username
                    ? Promise.resolve()
                    : Promise.reject(new Error("登录名不匹配")),
              },
            ]}
          >
            <Input autoComplete="off" />
          </AppField>
        )}
        <AppField
          name="reason"
          label="操作原因"
          rules={[
            { required: true },
            {
              validator: (_rule, value) => {
                const bytes = new TextEncoder().encode(
                  (value || "").trim(),
                ).length;
                return bytes >= 3 && bytes <= 500
                  ? Promise.resolve()
                  : Promise.reject(
                      new Error("操作原因须为 3–500 个 UTF-8 字节"),
                    );
              },
            },
          ]}
        >
          <Input autoComplete="off" />
        </AppField>
        <Reauthentication mfa={actor.mfaEnabled} prefix="管理员" />
      </AppForm>
    </TaskDialog>
  );
}
